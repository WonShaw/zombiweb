/**
 * 程序化枪模。约定：枪口朝 -z，原点在扳机附近，单位米。
 * sightY = 准星线相对原点的高度，开镜时把它对准屏幕中心（准星顶端正好卡在照门缺口里）。
 * 零件和材质在 parts.ts；每把枪建完后按材质合并成少量网格。
 */
export interface GunModel {
  group: THREE.Group;
  muzzle: THREE.Object3D;
  sightY: number;
}

type LeftHand =
  | { kind: 'support'; c: THREE.Vector3; hw: number; hh: number }
  | { kind: 'grip'; c: THREE.Vector3; angle: number; gw?: number }
  | { kind: 'cup' };

interface Info {
  muzzle: [number, number, number];
  sightY: number;
  /** 右手握把中心（中指高度）与握把后倾角 */
  right: THREE.Vector3;
  grip: number;
  /** 握把宽度 */
  gw?: number;
  left: LeftHand;
}

type Builder = (g: THREE.Group) => Info;

